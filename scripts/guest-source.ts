/**
 * The modules a session runtime's guest loads, which flake.nix turns into the
 * source an Apple Silicon guest build sees. Narrowing that source to the guest's
 * real import graph keeps host-only changes from changing the runtime identity
 * (and from asking every Mac to rebuild its runtime).
 *
 *   deno task runtime:guest-source          # rewrite packaging/macos/guest-source.json
 *   deno task runtime:guest-source --check  # fail if it no longer matches the graph
 */
import { fileURLToPath } from "node:url";
import { dirname, join, relative } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
export const guestSourceManifest = "packaging/macos/guest-source.json";

/** What the guest runs; everything else is reached from these. */
export const guestEntrypoints = [
  // packaging/runtimes/session.nix: the environment guest.
  "runtime/src/session-vm/guest.ts",
  // backend/daemon/src/daemon/isolated-worker.ts (guestWorkerArgv): beside guest.ts.
  "runtime/src/session-vm/guest-worker.ts",
] as const;

// Modules started by path rather than imported, e.g. `deno run` of a sibling file.
const launchedModule = /new URL\(\s*"(\.{1,2}\/[^"]+\.tsx?)",\s*import\.meta\.url\s*\)/g;

interface ModuleInfo {
  specifier: string;
  error?: string;
}

/** Repository-relative paths of every local module the guest can load, sorted. */
export const guestModules = async (): Promise<string[]> => {
  const found = new Set<string>();
  const pending: string[] = [...guestEntrypoints];
  while (pending.length) {
    const entry = pending.pop()!;
    if (found.has(entry)) continue;
    const info = await new Deno.Command(Deno.execPath(), {
      args: ["info", "--json", "--no-npm", "--no-remote", entry],
      cwd: root,
      stdin: "null",
      stdout: "piped",
      stderr: "piped",
    }).output();
    if (!info.success)
      throw new Error(`deno info ${entry} failed: ${new TextDecoder().decode(info.stderr)}`);
    const { modules } = JSON.parse(new TextDecoder().decode(info.stdout)) as {
      modules: ModuleInfo[];
    };
    for (const module of modules) {
      if (!module.specifier.startsWith("file://")) continue;
      const path = relative(root, fileURLToPath(module.specifier));
      if (module.error) throw new Error(`${path}: ${module.error}`);
      if (path.startsWith("..")) throw new Error(`Guest module outside the repository: ${path}`);
      if (found.has(path)) continue;
      found.add(path);
      for (const [, launched] of (await Deno.readTextFile(join(root, path))).matchAll(
        launchedModule,
      ))
        pending.push(relative(root, join(root, dirname(path), launched!)));
    }
  }
  return [...found].sort();
};

export const readGuestSourceManifest = async (): Promise<string[]> =>
  (JSON.parse(await Deno.readTextFile(join(root, guestSourceManifest))) as { modules: string[] })
    .modules;

if (import.meta.main) {
  const modules = await guestModules();
  if (Deno.args.includes("--check")) {
    const listed = await readGuestSourceManifest();
    if (JSON.stringify(listed) !== JSON.stringify(modules)) {
      console.error(
        `${guestSourceManifest} is out of date; run deno task runtime:guest-source and commit it.`,
      );
      Deno.exit(1);
    }
  } else {
    await Deno.writeTextFile(
      join(root, guestSourceManifest),
      JSON.stringify(
        {
          description:
            "Generated by `deno task runtime:guest-source`: the modules a session runtime guest loads. flake.nix builds the Apple Silicon guest source from them.",
          modules,
        },
        null,
        2,
      ) + "\n",
    );
    console.error(`${guestSourceManifest}: ${modules.length} modules`);
  }
}
